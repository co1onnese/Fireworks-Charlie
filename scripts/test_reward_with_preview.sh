#!/bin/bash
#
# Test reward function locally using reward-kit preview
#
# This script tests the reward function with sample data before deploying
# to Fireworks AI. It helps catch issues early and iterate quickly.
#
# Usage:
#   ./scripts/test_reward_with_preview.sh [num_samples]
#
# Examples:
#   ./scripts/test_reward_with_preview.sh        # Test with 5 samples
#   ./scripts/test_reward_with_preview.sh 10     # Test with 10 samples
#

set -e  # Exit on error

# Colors for output
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

# Configuration
PROJECT_ROOT="/opt/Fireworks-Charlie"
SAMPLES_FILE="${PROJECT_ROOT}/test_samples/preview_sample.jsonl"
REWARD_FUNCTION_DIR="${PROJECT_ROOT}/rlvr"
NUM_SAMPLES="${1:-5}"  # Default to 5 samples

echo -e "${BLUE}???????????????????????????????????????????????????????????????${NC}"
echo -e "${BLUE}  Testing Reward Function Locally with reward-kit preview${NC}"
echo -e "${BLUE}???????????????????????????????????????????????????????????????${NC}"
echo ""

# Check if virtual environment is activated
if [[ -z "$VIRTUAL_ENV" ]]; then
    echo -e "${YELLOW}Activating virtual environment...${NC}"
    source "${PROJECT_ROOT}/.venv/bin/activate"
fi

# Verify reward-kit is installed
if ! command -v reward-kit &> /dev/null; then
    echo -e "${RED}? reward-kit not found. Please install with: pip install fireworks-ai[reward-kit]${NC}"
    exit 1
fi

echo -e "${GREEN}? reward-kit CLI found${NC}"

# Verify sample file exists
if [[ ! -f "$SAMPLES_FILE" ]]; then
    echo -e "${RED}? Sample file not found: $SAMPLES_FILE${NC}"
    exit 1
fi

echo -e "${GREEN}? Sample file found: $SAMPLES_FILE${NC}"

# Verify reward function directory exists
if [[ ! -d "$REWARD_FUNCTION_DIR" ]]; then
    echo -e "${RED}? Reward function directory not found: $REWARD_FUNCTION_DIR${NC}"
    exit 1
fi

# Check which reward function file is being used
if [[ -L "${REWARD_FUNCTION_DIR}/reward_function.py" ]]; then
    ACTUAL_FILE=$(readlink -f "${REWARD_FUNCTION_DIR}/reward_function.py")
    echo -e "${GREEN}? Reward function (symlink): reward_function.py ? $(basename $ACTUAL_FILE)${NC}"
else
    echo -e "${GREEN}? Reward function: reward_function.py${NC}"
fi

echo ""
echo -e "${BLUE}Running preview with ${NUM_SAMPLES} samples...${NC}"
echo ""

# Run reward-kit preview
cd "$PROJECT_ROOT"
reward-kit preview \
    --samples "$SAMPLES_FILE" \
    --metrics-folders "stock_prediction=${REWARD_FUNCTION_DIR}" \
    --max-samples "$NUM_SAMPLES" \
    --verbose

# Check exit code
if [[ $? -eq 0 ]]; then
    echo ""
    echo -e "${GREEN}???????????????????????????????????????????????????????????????${NC}"
    echo -e "${GREEN}  ? Preview test completed successfully!${NC}"
    echo -e "${GREEN}???????????????????????????????????????????????????????????????${NC}"
    echo ""
    echo -e "${BLUE}Next steps:${NC}"
    echo -e "  1. Review the scores and metrics above"
    echo -e "  2. If satisfied, deploy with: ${GREEN}python rlvr_main.py deploy${NC}"
    echo -e "  3. Create new training job in Fireworks dashboard"
    echo ""
else
    echo ""
    echo -e "${RED}???????????????????????????????????????????????????????????????${NC}"
    echo -e "${RED}  ? Preview test failed!${NC}"
    echo -e "${RED}???????????????????????????????????????????????????????????????${NC}"
    echo ""
    echo -e "${YELLOW}Troubleshooting:${NC}"
    echo -e "  1. Check the error messages above"
    echo -e "  2. Verify reward function has no external imports"
    echo -e "  3. Test individual components: ${BLUE}python scripts/test_reward_advanced.py${NC}"
    echo -e "  4. Check logs in: ${BLUE}logs/fireworks_charlie_$(date +%Y%m%d).log${NC}"
    echo ""
    exit 1
fi
