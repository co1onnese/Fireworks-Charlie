#!/bin/bash
#
# Compare All Trading Strategies
# Tests all three strategies and generates comparison summary
#

set -e

MODEL_NAME="${1:-accounts/lstn/models/rftj-v1in37s4-evv0b}"
MAX_EXAMPLES="${2:-5}"

echo "????????????????????????????????????????????????????????????????????????"
echo "?                                                                      ?"
echo "?              Strategy Comparison - All Three Strategies              ?"
echo "?                                                                      ?"
echo "????????????????????????????????????????????????????????????????????????"
echo ""
echo "Model: $MODEL_NAME"
echo "Max Examples: $MAX_EXAMPLES"
echo ""
echo "??????????????????????????????????????????????????????????????????????"

# Activate virtual environment
source .venv/bin/activate

# Run each strategy
for strategy in A B C; do
    echo ""
    echo "??????????????????????????????????????????????????????????????????????"
    echo "Running Strategy $strategy..."
    echo "??????????????????????????????????????????????????????????????????????"
    echo ""
    
    python scripts/evaluate_model.py \
        --fine-tuned-model "$MODEL_NAME" \
        --max-examples "$MAX_EXAMPLES" \
        --strategy "$strategy"
    
    echo ""
done

echo ""
echo "??????????????????????????????????????????????????????????????????????"
echo "? All Strategies Completed!"
echo "??????????????????????????????????????????????????????????????????????"
echo ""
echo "?? Results Summary:"
echo ""

# Find the latest result files
for strategy in A B C; do
    latest_summary=$(ls -t outputs/evaluations/eval_strategy_${strategy}_*_summary.txt 2>/dev/null | head -1)
    
    if [ -f "$latest_summary" ]; then
        echo "Strategy $strategy Results:"
        grep -A 15 "COMPARISON" "$latest_summary" 2>/dev/null || echo "  (See $latest_summary for details)"
        echo ""
    fi
done

echo "??????????????????????????????????????????????????????????????????????"
echo "?? Full results saved in: outputs/evaluations/"
echo ""
echo "View detailed summaries:"
echo "  ls -lh outputs/evaluations/eval_strategy_*_summary.txt"
echo ""
echo "Compare strategies:"
echo "  for f in outputs/evaluations/eval_strategy_*_summary.txt; do"
echo "    echo \"=== \$f ===\";"
echo "    grep -A 5 \"COMPARISON\" \"\$f\";"
echo "    echo \"\";"
echo "  done"
echo "??????????????????????????????????????????????????????????????????????"
